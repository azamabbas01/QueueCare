from io import BytesIO

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
from xml.sax.saxutils import escape

NAVY = colors.HexColor("#002F84")
GREEN = colors.HexColor("#019E81")


def prescription_pdf(*, patient_name: str, doctor_name: str, specialty: str | None, department: str | None,
                     visit_date: str, token: str, items: list[dict], advice: str | None,
                     diagnosis: str | None) -> bytes:
    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm,
                            topMargin=16 * mm, bottomMargin=16 * mm, title="QueueCare prescription")
    base = getSampleStyleSheet()
    h = ParagraphStyle("h", parent=base["Title"], textColor=NAVY, fontSize=22, alignment=0, spaceAfter=2)
    sub = ParagraphStyle("s", parent=base["Normal"], textColor=GREEN, fontSize=10)
    body = ParagraphStyle("b", parent=base["Normal"], fontSize=10.5, leading=15)
    small = ParagraphStyle("sm", parent=base["Normal"], fontSize=8.5, textColor=colors.grey, leading=12)
    e = lambda v: escape(str(v or "—"))  # noqa: E731

    story = [
        Paragraph("QueueCare", h),
        Paragraph("Prescription", sub), Spacer(1, 8),
        Table([
            [Paragraph(f"<b>Patient</b><br/>{e(patient_name)}", body),
             Paragraph(f"<b>Doctor</b><br/>Dr. {e(doctor_name)}<br/>{e(specialty)}", body),
             Paragraph(f"<b>Visit</b><br/>{e(visit_date)}<br/>Token {e(token)}", body)],
        ], colWidths=[60 * mm, 62 * mm, 50 * mm], style=TableStyle([
            ("BOX", (0, 0), (-1, -1), 0.6, NAVY), ("INNERGRID", (0, 0), (-1, -1), 0.3, colors.lightgrey),
            ("VALIGN", (0, 0), (-1, -1), "TOP"), ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6)])),
        Spacer(1, 10),
    ]
    if diagnosis:
        story += [Paragraph(f"<b>Diagnosis:</b> {e(diagnosis)}", body), Spacer(1, 8)]
    rows = [["#", "Medicine", "Dose", "How often", "For how long", "Instructions"]]
    for i, item in enumerate(items, 1):
        rows.append([str(i)] + [Paragraph(e(item.get(k)), body) for k in
                                ("medicine", "dose", "frequency", "duration", "instructions")])
    if len(rows) == 1:
        rows.append(["", Paragraph("No medicines prescribed.", body), "", "", "", ""])
    story.append(Table(rows, colWidths=[8 * mm, 46 * mm, 22 * mm, 28 * mm, 26 * mm, 42 * mm], repeatRows=1,
                       style=TableStyle([
                           ("BACKGROUND", (0, 0), (-1, 0), NAVY), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                           ("FONTSIZE", (0, 0), (-1, -1), 9.5), ("GRID", (0, 0), (-1, -1), 0.3, colors.lightgrey),
                           ("VALIGN", (0, 0), (-1, -1), "TOP")])))
    if advice:
        story += [Spacer(1, 10), Paragraph(f"<b>Advice:</b> {e(advice)}", body)]
    story += [Spacer(1, 22), Paragraph(
        "Generated by QueueCare. This prescription is visible only to the patient and the treating doctor.", small)]
    doc.build(story)
    return buffer.getvalue()
